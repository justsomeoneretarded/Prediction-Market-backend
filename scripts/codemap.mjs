#!/usr/bin/env node
/**
 * codemap — a tiny, dependency-free "graphify" for this project.
 *
 * Scans the TypeScript sources of the API (this repo) and, if present, the web app
 * (../prediction-market-frontend), follows every relative/alias import, and writes:
 *   docs/graph/graph.json  — nodes (files: module, summary, exports, lines) + edges (imports)
 *   docs/graph/CODEMAP.md  — module dependency diagram (Mermaid) + a file index with summaries
 *
 * Summaries come from each file's first /** doc comment *\/ (or first // comment), so the map
 * stays accurate as long as files keep a one-paragraph header comment.
 *
 *   node scripts/codemap.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const repos = [
  { name: 'api', dir: path.join(root, 'src'), alias: null },
  { name: 'api-test', dir: path.join(root, 'test'), alias: null },
  { name: 'api-db', dir: path.join(root, 'prisma'), alias: null },
  { name: 'web', dir: path.resolve(root, '../prediction-market-frontend/src'), alias: '@/' },
];

const walk = (d) =>
  fs.existsSync(d)
    ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
        const p = path.join(d, e.name);
        if (e.isDirectory()) return e.name === 'node_modules' || e.name.startsWith('.') ? [] : walk(p);
        return /\.(ts|tsx|mjs)$/.test(e.name) && !e.name.endsWith('.d.ts') ? [p] : [];
      })
    : [];

const nodes = new Map();
const edges = [];

function summary(src) {
  const block = src.match(/\/\*\*([\s\S]*?)\*\//);
  let text = block ? block[1].split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).filter(Boolean).join(' ') : '';
  if (!text) text = (src.match(/^\s*\/\/\s*(.+)$/m)?.[1] ?? '').trim();
  return text.replace(/\s+/g, ' ').slice(0, 220);
}

for (const repo of repos) {
  for (const file of walk(repo.dir)) {
    const src = fs.readFileSync(file, 'utf8');
    const rel = path.relative(path.dirname(root), file);
    const sub = path.relative(repo.dir, file).split(path.sep);
    const moduleName = `${repo.name}/${sub.length > 1 ? sub[0] : '(root)'}`;
    const exports = [...src.matchAll(/export\s+(?:default\s+)?(?:async\s+)?(?:class|function|const|interface|type|enum)\s+(\w+)/g)].map((m) => m[1]);
    nodes.set(file, { id: rel, repo: repo.name, module: moduleName, summary: summary(src), exports, lines: src.split('\n').length });
    for (const m of src.matchAll(/(?:import|export)[^'"]*?from\s+['"]([^'"]+)['"]|require\(['"]([^'"]+)['"]\)|import\(['"]([^'"]+)['"]\)/g)) {
      const spec = m[1] ?? m[2] ?? m[3];
      let target = null;
      if (spec.startsWith('.')) target = path.resolve(path.dirname(file), spec);
      else if (repo.alias && spec.startsWith(repo.alias)) target = path.join(repo.dir, spec.slice(repo.alias.length));
      if (!target) continue;
      const hit = ['', '.ts', '.tsx', '/index.ts', '/index.tsx'].map((x) => target + x).find((p) => fs.existsSync(p) && fs.statSync(p).isFile());
      if (hit) edges.push({ from: file, to: hit });
    }
  }
}

// module-level graph
const modEdges = new Map();
for (const e of edges) {
  const a = nodes.get(e.from)?.module, b = nodes.get(e.to)?.module;
  if (!a || !b || a === b || a.startsWith('api-test')) continue;
  modEdges.set(`${a}→${b}`, (modEdges.get(`${a}→${b}`) ?? 0) + 1);
}
const mods = [...new Set([...nodes.values()].filter((n) => !n.module.startsWith('api-test')).map((n) => n.module))].sort();
const idOf = (m) => m.replace(/[^a-zA-Z0-9]/g, '_');

let md = `# Code map\n\n_Generated by \`node scripts/codemap.mjs\` — do not edit by hand._\n\n`;
md += `${nodes.size} files · ${edges.length} import edges · ${mods.length} modules\n\n`;
md += '## Module dependencies\n\n```mermaid\nflowchart LR\n';
for (const repo of ['api', 'api-db', 'web']) {
  const ms = mods.filter((m) => m.startsWith(repo + '/'));
  if (!ms.length) continue;
  md += `  subgraph ${idOf(repo)}["${repo}"]\n`;
  for (const m of ms) md += `    ${idOf(m)}["${m.split('/')[1]}"]\n`;
  md += '  end\n';
}
for (const [k] of modEdges) {
  const [a, b] = k.split('→');
  md += `  ${idOf(a)} --> ${idOf(b)}\n`;
}
md += '```\n\n## Files\n\n';
for (const m of [...new Set([...nodes.values()].map((n) => n.module))].sort()) {
  md += `### ${m}\n\n| File | Lines | Exports | What it does |\n|---|---:|---|---|\n`;
  for (const n of [...nodes.values()].filter((x) => x.module === m).sort((a, b) => a.id.localeCompare(b.id))) {
    md += `| \`${n.id}\` | ${n.lines} | ${n.exports.slice(0, 6).join(', ')} | ${n.summary.replace(/\|/g, '\\|')} |\n`;
  }
  md += '\n';
}

const out = path.join(root, 'docs/graph');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, 'graph.json'),
  JSON.stringify({ generatedBy: 'scripts/codemap.mjs', nodes: [...nodes.values()], edges: edges.map((e) => ({ from: nodes.get(e.from).id, to: nodes.get(e.to).id })), modules: [...modEdges].map(([k, w]) => ({ edge: k, imports: w })) }, null, 1),
);
fs.writeFileSync(path.join(out, 'CODEMAP.md'), md);
console.log(`codemap: ${nodes.size} files, ${edges.length} edges → docs/graph/`);
